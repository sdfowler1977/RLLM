//! Clean-room feature rebuild from an observer specification.
//! The reference is cited, then a new skeleton is generated from that
//! specification and checked by running the same observer again.
//! Nothing here executes the subject or copies its bytes.
use std::collections::BTreeMap;
use std::path::Path;
use super::js_evidence;
use super::super::rust_source_observation;

pub(super) const SPEC_ITEM_CAP: usize = 48;
pub(super) const SPEC_BYTE_CAP: usize = 48 * 1024;
pub(super) const GENERATED_BYTE_CAP: usize = 48 * 1024;
pub(super) const SUBJECT_BYTE_CAP: usize = 128 * 1024;
pub(super) const ITEM_CAP_NAME: &str = "clean-room item cap";
pub(super) const SPEC_BYTE_NAME: &str = "clean-room spec-size cap";
pub(super) const GENERATED_BYTE_NAME: &str = "clean-room generated-byte cap";
pub(super) const SUBJECT_BYTE_NAME: &str = "clean-room subject-byte cap";
pub(super) const EMPTY_NAME: &str = "clean-room subject observation is empty";
pub(super) const COPY_NAME: &str = "clean-room copy";

#[derive(Clone, Copy, PartialEq, Eq)]
enum Subject { Script, Package, Rust }

enum Item {
    Edge { form: String, specifier: Option<String>, offset: usize },
    Site { kind: String, value: String, offset: usize },
    Declaration { description: String, line: usize, column: usize },
    Package { field: String, fact: String },
}

struct Gap { id: String, location: String, reason: String }

pub(super) struct Citation {
    pub path: String,
    pub dev: String,
    pub ino: String,
    pub size: String,
    pub sha256: String,
    pub record: String,
    pub snapshot: String,
    pub node: String,
    pub path_hex: String,
}

#[derive(Debug)]
pub(super) struct Outcome {
    pub generated: String,
    pub lines: String,
    pub items: usize,
    pub matched: usize,
    pub missing: usize,
    pub unknown: usize,
}

fn refusal(name: &str, detail: &str) -> String {
    format!("Refusal: {name}. {detail} No output was written.")
}

pub(super) fn admit(size: usize, cap: usize, name: &str) -> Result<(), String> {
    if size > cap { Err(refusal(name, &format!("{size} exceeds {cap}"))) } else { Ok(()) }
}

pub(super) fn reject_identical(generated: &[u8], reference: &[u8]) -> Result<(), String> {
    if generated == reference {
        Err(refusal(COPY_NAME, "Generated bytes are identical to the reference."))
    } else {
        Ok(())
    }
}

fn flat(value: &str) -> String { value.replace(['\n', '\r'], " ") }

fn claim(status: &str, id: &str, known: &str, unknown: &str) -> String {
    format!("{status} {}: known: {}. unknown: {}.\n", flat(id), flat(known), flat(unknown))
}

fn cite_place(citation: &Citation) -> String {
    format!("path {} dev {} ino {} size {} sha256 {}", flat(&citation.path), flat(&citation.dev), flat(&citation.ino), flat(&citation.size), flat(&citation.sha256))
}

impl Item {
    fn id(&self) -> String {
        match self {
            Item::Edge { form, specifier, .. } => format!("edge {form} {}", specifier.as_deref().unwrap_or("local")),
            Item::Site { kind, value, .. } => format!("site {kind} {value}"),
            Item::Declaration { description, .. } => format!("declaration {description}"),
            Item::Package { field, fact, .. } => format!("package {field} {fact}"),
        }
    }
    fn detail(&self) -> String {
        match self {
            Item::Edge { form, offset, .. } => format!("byte {offset} form {form}"),
            Item::Site { kind, offset, .. } => format!("byte {offset} site {kind}"),
            Item::Declaration { line, column, .. } => format!("line {line} byte-column {column}; the Rust observer records a line and byte column, not a file byte offset"),
            Item::Package { field, fact, .. } => format!("package field {field} fact {fact}"),
        }
    }
    fn spec_unknown(&self) -> &'static str {
        match self {
            Item::Declaration { .. } => "function bodies, types, and cfg were not in the lexical observation",
            Item::Package { .. } => "other package fields and runtime resolution were not in the observation",
            _ => "local bindings, function bodies, and runtime resolution were not in the observation",
        }
    }
}

fn classify(path: &str) -> Result<Subject, String> {
    let path_ref = Path::new(path);
    match js_evidence::node_kind(path_ref) {
        Some(js_evidence::Kind::Asar) => Err(refusal("clean-room asar container", "An asar container is not a feature source. No listing was generated.")),
        Some(js_evidence::Kind::Package) => Ok(Subject::Package),
        Some(js_evidence::Kind::Script) => Ok(Subject::Script),
        None if path_ref.extension().and_then(|ext| ext.to_str()) == Some("rs") => Ok(Subject::Rust),
        None => Err(refusal("clean-room subject kind", "The reference path is not a JavaScript, package.json, or Rust subject.")),
    }
}

fn announced(line: &str, prefix: &str, suffix: &str) -> Option<usize> {
    line.strip_prefix(prefix).and_then(|rest| rest.strip_suffix(suffix)).and_then(|n| n.parse().ok())
}

fn bad_line(kind: &str, line: &str) -> String {
    refusal("clean-room observation line", &format!("{kind} line is not readable: {line}"))
}

fn parse_edge(line: &str) -> Result<Item, String> {
    let (form, rest) = line.split_once(" at byte ").ok_or_else(|| bad_line("edge", line))?;
    if form.is_empty() || !form.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '(' | ')' | '.')) {
        return Err(bad_line("edge", line));
    }
    let (offset_text, tail) = rest.split_once(' ').ok_or_else(|| bad_line("edge", line))?;
    let offset: usize = offset_text.parse().map_err(|_| bad_line("edge", line))?;
    let specifier = if tail == "local form, no external specifier." {
        None
    } else if let Some(value) = tail.strip_prefix("specifier \"").and_then(|value| value.strip_suffix("\".")) {
        if value.contains('"') { return Err(refusal("clean-room specifier", "A quoted specifier cannot be cited from the observation text.")); }
        Some(value.to_string())
    } else {
        return Err(bad_line("edge", line));
    };
    Ok(Item::Edge { form: form.to_string(), specifier, offset })
}

fn parse_site(line: &str) -> Result<Item, String> {
    let (kind, rest) = line.split_once(" at byte ").ok_or_else(|| bad_line("site", line))?;
    if kind.is_empty() || !kind.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_')) {
        return Err(bad_line("site", line));
    }
    let (offset_text, tail) = rest.split_once(' ').ok_or_else(|| bad_line("site", line))?;
    let offset: usize = offset_text.parse().map_err(|_| bad_line("site", line))?;
    let Some(value) = tail.strip_prefix("literal \"").and_then(|value| value.strip_suffix("\".")) else { return Err(bad_line("site", line)); };
    if value.contains('"') { return Err(refusal("clean-room string site", "A quoted census value cannot be cited from the observation text.")); }
    Ok(Item::Site { kind: kind.to_string(), value: value.to_string(), offset })
}

fn parse_unknown(line: &str) -> Result<Gap, String> {
    let Some(rest) = line.strip_prefix("Unknown at byte ") else { return Err(bad_line("unknown", line)); };
    let Some((offset_text, reason)) = rest.split_once(": ") else { return Err(bad_line("unknown", line)); };
    let offset: usize = offset_text.parse().map_err(|_| bad_line("unknown", line))?;
    let reason = reason.strip_suffix('.').unwrap_or(reason);
    Ok(Gap { id: format!("unknown-byte {offset}"), location: format!("byte {offset}"), reason: reason.to_string() })
}

fn parse_fact(line: &str) -> Result<Option<Item>, String> {
    let Some((field, rest)) = line.split_once(": ") else { return Ok(None) };
    if !matches!(field, "name" | "version" | "main" | "module" | "electron") { return Ok(None); }
    if rest == "absent" { return Ok(Some(Item::Package { field: field.into(), fact: "absent".into() })); }
    if let Some(value) = rest.strip_prefix("present \"").and_then(|value| value.strip_suffix('"')) {
        if value.contains('"') { return Err(refusal("clean-room package value", "A quoted package fact cannot be cited from the observation text.")); }
        return Ok(Some(Item::Package { field: field.into(), fact: value.into() }));
    }
    if rest.starts_with("unknown (") && rest.ends_with(')') {
        return Err(refusal("clean-room package fact is unknown", &format!("{field} {rest}")));
    }
    Err(bad_line("package fact", line))
}

fn room_for(len: usize) -> Result<(), String> {
    if len >= SPEC_ITEM_CAP {
        Err(refusal(ITEM_CAP_NAME, &format!("{} exceeds {SPEC_ITEM_CAP}", len + 1)))
    } else {
        Ok(())
    }
}

fn append_report(spec_len: usize, lines: &mut String, line: &str) -> Result<(), String> {
    admit(spec_len.saturating_add(lines.len()).saturating_add(line.len()), SPEC_BYTE_CAP, SPEC_BYTE_NAME)?;
    lines.push_str(line);
    Ok(())
}

fn observe_items(bytes: &[u8], subject: Subject) -> Result<(Vec<Item>, Vec<Gap>), String> {
    match subject {
        Subject::Rust => parse_rust(&rust_source_observation::analyze(bytes, true)),
        Subject::Script => parse_script(&js_evidence::observe(bytes, js_evidence::Kind::Script, true).text),
        Subject::Package => parse_package(&js_evidence::observe(bytes, js_evidence::Kind::Package, true).text),
    }
}

fn parse_script(text: &str) -> Result<(Vec<Item>, Vec<Gap>), String> {
    let mut items = Vec::new();
    let mut gaps = Vec::new();
    let mut section = "";
    let mut edges = None;
    let mut sites = None;
    let mut unknowns = None;
    let mut parsed_unknowns = 0usize;
    for line in text.lines() {
        if let Some(count) = announced(line, "Module graph: ", " edges.") { section = "graph"; edges = Some(count); continue; }
        if let Some(count) = announced(line, "Unknowns: ", ".") { section = "unknowns"; unknowns = Some(count); continue; }
        if let Some(count) = announced(line, "String census: ", " sites.") { section = "census"; sites = Some(count); continue; }
        if line.starts_with("Source maps:") { section = "maps"; continue; }
        if let Some(reason) = line.strip_prefix("Refusal: ") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: format!("refusal {}", gaps.len()), location: "observer refusal".into(), reason: reason.trim_end_matches('.').into() });
            continue;
        }
        if line.starts_with("Retained bytes are not UTF-8") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: "script-utf8".into(), location: "retained bytes".into(), reason: line.into() });
            continue;
        }
        match section {
            "graph" => {
                room_for(items.len())?;
                items.push(parse_edge(line)?);
            }
            "unknowns" => {
                room_for(gaps.len())?;
                gaps.push(parse_unknown(line)?);
                parsed_unknowns += 1;
            }
            "census" => {
                room_for(items.len())?;
                items.push(parse_site(line)?);
            }
            "maps" if line.starts_with("Reference at byte ") || line.starts_with("Unknown at byte ") => {
                room_for(gaps.len())?;
                gaps.push(Gap { id: format!("source-map {}", gaps.len()), location: "source map".into(), reason: line.into() });
            }
            _ => {}
        }
    }
    if edges.is_none() { return Err(refusal("clean-room module graph", "The script observation has no module-graph count.")); }
    let edge_count = items.iter().filter(|item| matches!(item, Item::Edge { .. })).count();
    let site_count = items.iter().filter(|item| matches!(item, Item::Site { .. })).count();
    if edges != Some(edge_count) || sites != Some(site_count) || unknowns != Some(parsed_unknowns) {
        return Err(refusal("clean-room observation count", "A script section count does not match the parsed rows."));
    }
    Ok((items, gaps))
}

fn parse_package(text: &str) -> Result<(Vec<Item>, Vec<Gap>), String> {
    let mut items = Vec::new();
    let mut gaps = Vec::new();
    if !text.lines().any(|line| line == "Kind: package.json") {
        return Err(refusal("clean-room package observation", "The package observer did not report a package.json node."));
    }
    for line in text.lines() {
        if let Some(reason) = line.strip_prefix("Refusal: ") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: format!("refusal {}", gaps.len()), location: "observer refusal".into(), reason: reason.trim_end_matches('.').into() });
            continue;
        }
        if line.contains("facts withheld") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: "package-withheld".into(), location: "package.json".into(), reason: line.into() });
            continue;
        }
        if let Some((field, _)) = line.split_once(": ") {
            if matches!(field, "name" | "version" | "main" | "module" | "electron") {
                room_for(items.len())?;
            }
        }
        if let Some(item) = parse_fact(line)? {
            items.push(item);
        }
    }
    Ok((items, gaps))
}

fn parse_rust_line(rest: &str) -> Result<Item, String> {
    let Some((location, description)) = rest.split_once(": ") else { return Err(bad_line("declaration", rest)); };
    let Some((line_text, column_text)) = location.split_once(", byte column ") else { return Err(bad_line("declaration", rest)); };
    let line: usize = line_text.parse().map_err(|_| bad_line("declaration", rest))?;
    let column: usize = column_text.parse().map_err(|_| bad_line("declaration", rest))?;
    if description.is_empty() { return Err(bad_line("declaration", rest)); }
    Ok(Item::Declaration { description: description.to_string(), line, column })
}

fn parse_rust(text: &str) -> Result<(Vec<Item>, Vec<Gap>), String> {
    let mut items = Vec::new();
    let mut gaps = Vec::new();
    let mut saw_count = false;
    for line in text.lines() {
        if let Some(reason) = line.strip_prefix("Lexical limitation: ") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: format!("lexical {}", gaps.len()), location: "lexical limitation".into(), reason: reason.into() });
            continue;
        }
        if line.contains("Report abbreviated") {
            room_for(gaps.len())?;
            gaps.push(Gap { id: "rust-report-abbreviated".into(), location: "lexical report".into(), reason: line.into() });
            continue;
        }
        if let Some(rest) = line.strip_prefix("Observed ") {
            saw_count = true;
            if let Some((total, after)) = rest.split_once(' ') {
                if let Some(shown) = after.split("displayed ").nth(1).and_then(|value| value.split([' ', '(']).next()) {
                    if total != shown {
                        room_for(gaps.len())?;
                        gaps.push(Gap { id: "rust-record-cap".into(), location: "lexical record cap".into(), reason: line.into() });
                    }
                }
            }
            continue;
        }
        if let Some(rest) = line.strip_prefix("Line ") {
            room_for(items.len())?;
            items.push(parse_rust_line(rest)?);
        }
    }
    if !saw_count { return Err(refusal("clean-room rust observation", "The Rust observer did not report a declaration count.")); }
    Ok((items, gaps))
}

fn spec_lines(items: &[Item], citation: &Citation) -> Result<String, String> {
    let mut out = String::new();
    for item in items {
        let known = format!("{} {}", cite_place(citation), item.detail());
        let line = claim("spec", &item.id(), &known, item.spec_unknown());
        append_report(0, &mut out, &line)?;
    }
    Ok(out)
}

fn js_escape(value: &str) -> String {
    let mut out = String::new();
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => out.push_str(&format!("\\u{{{:x}}}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

fn json_escape(value: &str) -> String {
    let mut out = String::new();
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            c if c.is_control() => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out
}

fn header(path: &str, sha: &str) -> String {
    let path = flat(path).replace("sourceMappingURL", "source-map-directive");
    format!("// clean-room implementation of {path}\n// known: observer specification sha256 {sha}\n// unknown: bodies and local bindings were not copied\n")
}

fn plain_name(name: &str) -> bool {
    !name.is_empty() && !name.chars().any(|c| c.is_whitespace() || matches!(c, '"' | '\\' | '{' | '}' | ';' | '(' | ')' | '\n' | '\r'))
}

fn emit_declaration(description: &str) -> Option<String> {
    if description.contains("[header prefix only]") { return None; }
    if let Some(name) = description.strip_prefix("fn ") { if plain_name(name) { return Some(format!("fn {name}() {{}}\n")); } }
    if let Some(name) = description.strip_prefix("struct ") { if plain_name(name) { return Some(format!("struct {name};\n")); } }
    if let Some(name) = description.strip_prefix("enum ") { if plain_name(name) { return Some(format!("enum {name} {{}}\n")); } }
    if let Some(name) = description.strip_prefix("trait ") { if plain_name(name) { return Some(format!("trait {name} {{}}\n")); } }
    if let Some(rest) = description.strip_prefix("mod ") {
        if let Some(name) = rest.strip_suffix("; external module declaration, file/path attributes unresolved") { if plain_name(name) { return Some(format!("mod {name};\n")); } }
        if let Some(name) = rest.strip_suffix("; inline module body begins") { if plain_name(name) { return Some(format!("mod {name} {{}}\n")); } }
        return None;
    }
    if let Some(tokens) = description.strip_prefix("use unresolved import tokens: ") { return Some(format!("use {tokens};\n")); }
    if let Some(tokens) = description.strip_prefix("impl unresolved implementation header tokens: ") { return Some(format!("impl {tokens} {{}}\n")); }
    None
}

fn emit_item(subject: Subject, item: &Item) -> Result<Option<String>, String> {
    match (subject, item) {
        (Subject::Script, Item::Edge { form, specifier, .. }) => {
            let line = match form.as_str() {
                "require" => format!("require(\"{}\");\n", js_escape(specifier.as_deref().ok_or_else(|| refusal("clean-room require", "A require edge has no specifier."))?)),
                "import" => format!("import \"{}\";\n", js_escape(specifier.as_deref().ok_or_else(|| refusal("clean-room import", "An import edge has no specifier."))?)),
                "import()" => format!("import(\"{}\");\n", js_escape(specifier.as_deref().ok_or_else(|| refusal("clean-room import()", "An import() edge has no specifier."))?)),
                "export" => match specifier {
                    Some(value) => format!("export {{}} from \"{}\";\n", js_escape(value)),
                    None => "export function rebuilt() {}\n".into(),
                },
                other => return Err(refusal("clean-room module form", &format!("{other} is not generated."))),
            };
            Ok(Some(line))
        }
        (Subject::Script, Item::Site { kind, value, .. }) => {
            if !kind.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_')) {
                return Err(refusal("clean-room string site", &format!("{kind} is not a generated call.")));
            }
            Ok(Some(format!("{kind}(\"{}\", function () {{}});\n", js_escape(value))))
        }
        (Subject::Rust, Item::Declaration { description, .. }) => Ok(emit_declaration(description)),
        (Subject::Package, Item::Package { field, fact, .. }) => {
            if fact == "absent" { return Ok(None); }
            if !field.chars().all(|c| c.is_ascii_alphanumeric() || c == '_') { return Err(refusal("clean-room package field", &format!("{field} is not emitted."))); }
            Ok(Some(format!("\"{}\":\"{}\"", json_escape(field), json_escape(fact))))
        }
        _ => Err(refusal("clean-room generator", "The item does not belong to the reference kind.")),
    }
}

fn generate(subject: Subject, items: &[Item], citation: &Citation) -> Result<String, String> {
    match subject {
        Subject::Package => {
            let mut rows = Vec::new();
            for item in items {
                if let Some(row) = emit_item(subject, item)? { rows.push(row); }
            }
            rows.push("\"clean_room\":\"generated\"".into());
            Ok(format!("{{\n{}\n}}\n", rows.join(",\n")))
        }
        Subject::Script | Subject::Rust => {
            let mut body = header(&citation.path, &citation.sha256);
            let mut statements = 0usize;
            for item in items {
                if let Some(line) = emit_item(subject, item)? { body.push_str(&line); statements += 1; }
            }
            if statements == 0 { return Err(refusal("clean-room generator", "No implementation statements could be derived from the specification.")); }
            Ok(body)
        }
    }
}

fn verify_parsed(subject: Subject, items: &[Item], gaps: &[Gap], generated: &[u8], citation: &Citation, spec_len: usize) -> Result<Outcome, String> {
    let (found, found_gaps) = observe_items(generated, subject)?;
    if !found_gaps.is_empty() && found_gaps.iter().any(|gap| gap.id.starts_with("refusal") || gap.id == "rust-record-cap" || gap.id == "rust-report-abbreviated") {
        return Err(refusal("clean-room generated observation", "The observer refused or abbreviated the generated artifact."));
    }
    let mut have: BTreeMap<String, usize> = BTreeMap::new();
    for item in &found { *have.entry(item.id()).or_default() += 1; }
    let mut lines = String::new();
    let mut matched = 0usize;
    let mut missing = 0usize;
    for item in items {
        let id = item.id();
        let known = format!("{} {}", cite_place(citation), item.detail());
        if have.get(&id).copied().unwrap_or(0) > 0 {
            let left = have.get_mut(&id).unwrap();
            *left -= 1;
            if *left == 0 { have.remove(&id); }
            matched += 1;
            append_report(spec_len, &mut lines, &claim("matched", &id, &known, "the generated skeleton shows this observer item and is not the reference body"))?;
        } else {
            missing += 1;
            append_report(spec_len, &mut lines, &claim("missing", &id, &known, "the generated file's observer does not show this item"))?;
        }
    }
    let mut unknown = 0usize;
    for gap in gaps {
        unknown += 1;
        let known = format!("{} {}", cite_place(citation), gap.location);
        append_report(spec_len, &mut lines, &claim("unknown", &gap.id, &known, &gap.reason))?;
    }
    for (id, count) in have {
        for _ in 0..count {
            unknown += 1;
            let known = format!("the generated file's observer recorded this item; reference sha256 {}", citation.sha256);
            append_report(spec_len, &mut lines, &claim("unknown", &id, &known, "it was not in the reference specification"))?;
        }
    }
    Ok(Outcome { generated: String::from_utf8(generated.to_vec()).map_err(|_| refusal("clean-room generated text", "The generated artifact is not UTF-8."))?, lines, items: items.len(), matched, missing, unknown })
}

fn guarded(bytes: &[u8], path: &str) -> Result<(Subject, Vec<Item>, Vec<Gap>), String> {
    admit(bytes.len(), SUBJECT_BYTE_CAP, SUBJECT_BYTE_NAME)?;
    let subject = classify(path)?;
    let (items, gaps) = observe_items(bytes, subject)?;
    if items.len() > SPEC_ITEM_CAP { return Err(refusal(ITEM_CAP_NAME, &format!("{} exceeds {SPEC_ITEM_CAP}", items.len()))); }
    if gaps.len() > SPEC_ITEM_CAP { return Err(refusal(ITEM_CAP_NAME, &format!("{} exceeds {SPEC_ITEM_CAP}", gaps.len()))); }
    if items.is_empty() {
        let extra = if gaps.is_empty() { String::from("No implementation items were observed.") } else { format!("Observed gaps: {}.", gaps.iter().map(|gap| gap.reason.as_str()).collect::<Vec<_>>().join("; ")) };
        return Err(format!("Refusal: {EMPTY_NAME}. {extra} No output was written."));
    }
    Ok((subject, items, gaps))
}

pub(super) fn rebuild(bytes: &[u8], path: &str, citation: &Citation) -> Result<Outcome, String> {
    let (subject, items, gaps) = guarded(bytes, path)?;
    let spec = spec_lines(&items, citation)?;
    admit(spec.len(), SPEC_BYTE_CAP, SPEC_BYTE_NAME)?;
    let generated = generate(subject, &items, citation)?;
    admit(generated.len(), GENERATED_BYTE_CAP, GENERATED_BYTE_NAME)?;
    reject_identical(generated.as_bytes(), bytes)?;
    let mut outcome = verify_parsed(subject, &items, &gaps, generated.as_bytes(), citation, spec.len())?;
    outcome.lines.insert_str(0, &spec);
    admit(outcome.lines.len(), SPEC_BYTE_CAP, SPEC_BYTE_NAME)?;
    outcome.generated = generated;
    Ok(outcome)
}

pub(super) fn verify_artifact(reference: &[u8], path: &str, generated: &[u8], citation: &Citation) -> Result<Outcome, String> {
    let (subject, items, gaps) = guarded(reference, path)?;
    let spec = spec_lines(&items, citation)?;
    admit(spec.len(), SPEC_BYTE_CAP, SPEC_BYTE_NAME)?;
    let mut outcome = verify_parsed(subject, &items, &gaps, generated, citation, spec.len())?;
    outcome.lines.insert_str(0, &spec);
    admit(outcome.lines.len(), SPEC_BYTE_CAP, SPEC_BYTE_NAME)?;
    Ok(outcome)
}
